"use client";

import { useEffect, useState } from "react";
import type { VideoContent } from "./types";

const cache = new Map<string, Promise<VideoContent | null>>();

function load(id: string): Promise<VideoContent | null> {
  let pending = cache.get(id);
  if (!pending) {
    pending = fetch(`/api/video/${id}`)
      .then((res) => (res.ok ? (res.json() as Promise<VideoContent>) : null))
      .catch(() => null);
    cache.set(id, pending);
    // Do not keep failures around, the next mount should retry.
    pending.then((content) => {
      if (!content) cache.delete(id);
    });
  }
  return pending;
}

/** Subtitles, translations and glosses of a video. Fetched once, never regenerated by AI. */
export function useVideoContent(id: string): VideoContent | null {
  const [content, setContent] = useState<VideoContent | null>(null);

  useEffect(() => {
    let cancelled = false;
    load(id).then((c) => {
      if (!cancelled && c) setContent(c);
    });
    return () => {
      cancelled = true;
    };
  }, [id]);

  // A slide that is handed another video must not show the previous one's subtitles while the new ones load.
  return content?.id === id ? content : null;
}
